"""
投资控股型平台公司信用资质分析提示词模板
三层穿透、八维分析框架
"""

CREDIT_ANALYSIS_PROMPT = """你是一位专业的信用分析师，擅长对投资控股型平台公司进行信用资质分析。请基于以下研报内容，按照"三层穿透、八维分析"框架进行深度分析。

## 分析框架

### 一、三层穿透分析

**第一层：母公司**
- 资产质量：长期股权投资占比、股权质押情况
- 债务压力：有息债务规模及结构、期限结构
- 现金流来源：是否依赖子公司分红/股东支持

**第二层：核心子公司**
- 经营状况：主营业务、市场地位
- 盈利能力：净利润、毛利率
- 是否为优质资产

**第三层：股东**
- 支持意愿：历史支持记录
- 支持能力：资产注入、资金拆借、增信

### 二、八维度分析

**维度一：战略定位与股东背景**
- 控股股东是谁？持股比例多少？
- 实际控制人是谁？（省/市国资委、央企、其他）
- 在集团内部的战略定位是什么？

**维度二：业务结构拆解**
- 现金流贡献板块：能提供稳定现金流的业务
- 亏损拖累板块：吞噬现金或侵蚀利润的业务
- 风险积累板块：高杠杆、高增长、周期性业务

**维度三：母公司口径财务分析**
- 长期股权投资占总资产比重
- 有息债务规模及结构
- 取得投资收益收到的现金

**维度四：合并口径财务分析**
- 资产质量：固定资产、无形资产占比
- 盈利能力：利润来源拆解
- 现金流质量：剔除资金归集影响后的经营现金流

**维度五：资金流向与勾稽关系**
- 资金来源端：银行借款、股东借款、债券融资
- 资金占用端：固定资产、长期股权投资、长期应收款
- 勾稽验证：股东借款去向

**维度六：再融资能力分析**
- 银行授信：总额、已使用、未使用
- 债券市场认可度：存续债券规模、利率
- 股权质押融资空间

**维度七：外部支持分析**
- 股东支持历史：资产注入、低成本借款
- 集团实力：控股股东信用资质
- 内部协同：业务依赖度

**维度八：评级一致性比对**
- 可比主体选择
- 比对维度：资产规模、负债率、盈利能力

### 三、核心要点总结
1. 切忌迷信合并报表：母公司口径才是核心
2. 穿透业务看本质：投资收益是"躺赚"还是"真赚"？
3. 追踪资金流向：构建"资金来源-资金占用"勾稽关系
4. 量化股东支持：将股东借款视为准资本

### 四、分层偿债来源评估
- 第一偿债来源：再融资能力（银行授信、债券市场、股东借款、股权质押）
- 第二偿债来源：资产变现/盘活能力
- 第三偿债来源：自身经营现金流
- 最终支撑：股东支持

---

## 研报内容

{file_content}

---

请按照上述框架，输出结构化的分析报告。每个维度需要包含：
1. 关键指标表格
2. 分析结论
3. 风险提示（如有）

输出格式要求：
- 使用 Markdown 格式
- 每个维度用二级标题分隔
- 关键数据用表格呈现
- 风险点用红色标注或加粗强调
"""

def get_credit_analysis_prompt(file_content: str) -> str:
    """生成信用资质分析提示词"""
    return CREDIT_ANALYSIS_PROMPT.format(file_content=file_content[:10000])  # 限制内容长度
